'use strict';
const assert=require('node:assert/strict');
const {observeOrders}=require('../scripts/collect_binance.cjs');
const read=Date.parse('2026-11-08T14:00:00Z'), iso=ms=>new Date(ms).toISOString();
const row={symbol:'ETHUSDT',side:'BUY',positionSide:'LONG',type:'LIMIT',executedQty:'0',avgPrice:'0',totalPnl:'0',orderTime:read-5000,orderUpdateTime:read-5000};
const page={list:[{...row,orderId:'9007199254740993'},row,row]};
const initial=observeOrders(page,null,iso(read));
assert.equal(initial[0].observation,'baseline');
assert.equal(initial[1].firstSeenAt,undefined);
assert.equal(initial.length,3);
assert.equal(initial[1].sampleFirstSeenAt,undefined);
const one=observeOrders({list:[row]},null,iso(read));
const repeated=observeOrders({list:[row]},{status:'ready',fetchedAt:iso(read),rows:one},iso(read+1000));
assert.equal(repeated[0].sampleFirstSeenAt,iso(read));
assert.equal(repeated[0].observation,undefined);
const prior={status:'ready',fetchedAt:iso(read),rows:initial};
const next={list:[...page.list,{...row,orderId:'2',orderTime:read+2000}]};
const updated=observeOrders(next,prior,iso(read+3000));
assert.equal(updated[0].firstSeenAt,iso(read));
assert.equal(updated[3].observation,'new_order');
assert.equal(observeOrders(next,prior,iso(read+3610000))[3].observation,'baseline');
assert.throws(()=>observeOrders({list:[page.list[0],page.list[0]]},prior,iso(read+3000)));
console.log('PASS order baseline, identity, first discovery, duplicates and observation gaps');
