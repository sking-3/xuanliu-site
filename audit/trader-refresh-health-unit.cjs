'use strict';
const assert = require('node:assert/strict');
const { makeHealth } = require('../scripts/trader-refresh-health.cjs');
const at = '2026-11-17T00:00:00.000Z';
const previous = {schemaVersion:1, platforms:{OKX:{lastCompletedAt:'2026-11-16T00:00:00.000Z'}}};
const read = file => file === 'scripts/source-holds.json' ? {binancePublicCollector:'paused',githubRunInventory:'stopped'} : file === 'trader/okx/period-returns.json' ? {generatedAt:at} : null;
const health = makeHealth(previous, {REFRESH_MODE:'positions', OKX_OUTCOME:'skipped', OKX_POSITIONS_OUTCOME:'skipped', BITGET_OUTCOME:'failure', HYPERLIQUID_OUTCOME:'success'}, at, read);
assert.equal(health.platforms.OKX.outcome, 'skipped');
assert.equal(health.platforms.OKX.lastCompletedAt, '2026-11-16T00:00:00.000Z');
assert.equal(health.platforms.Bitget.outcome, 'failure');
assert.equal(health.platforms.Hyperliquid.lastCompletedAt, at);
assert.equal(health.platforms.Binance.outcome, 'stopped');
assert.equal(makeHealth(null, {OKX_OUTCOME:'success', OKX_POSITIONS_OUTCOME:'failure'}, at).platforms.OKX.outcome, 'failure');
assert.equal(makeHealth(null, {OKX_OUTCOME:'success', OKX_POSITIONS_OUTCOME:'skipped'}, at).platforms.OKX.outcome, 'unknown');
assert.ok(health.platforms.OKX.dataAt);
const withStop = file => file === 'trader/bitget/source-stop.json' ? {status:'stopped',reason:'http_429',at} : read(file);
const stopped = makeHealth(null, {BITGET_OUTCOME:'success'}, at, withStop).platforms.Bitget;
assert.equal(stopped.outcome, 'stopped');
assert.equal(stopped.stopReason, 'http_429');
assert.equal(stopped.lastCompletedAt, null);
const allowedPolicy = file => file === 'scripts/source-holds.json' ? {binancePublicCollector:'approved', githubRunInventory:'approved'} : null;
assert.equal(makeHealth(null, {BINANCE_GUARD_ALLOWED:'false'}, at, allowedPolicy).platforms.Binance.stopReason, 'source_guard');
assert.equal(makeHealth(null, {HYPERLIQUID_ALLOWED:'false'}, at, read).platforms.Hyperliquid.outcome, 'stopped');
console.log('trader refresh health tests passed');
